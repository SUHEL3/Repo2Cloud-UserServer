package org.example.repo2cloud.client;

import org.example.repo2cloud.dto.build_server_DTO.DeployRequestDto;
import org.example.repo2cloud.dto.build_server_DTO.DeploymentDto;
import org.example.repo2cloud.dto.build_server_DTO.DeploymentLogDto;
import org.example.repo2cloud.dto.build_server_DTO.DeploymentResponseDto;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.service.annotation.DeleteExchange;
import org.springframework.web.service.annotation.GetExchange;
import org.springframework.web.service.annotation.PostExchange;

import java.util.List;

/**
 * HTTP Service Interface for communicating with the Build Server.
 *
 * <p>A runtime proxy is generated by {@link org.springframework.web.service.invoker.HttpServiceProxyFactory}
 * backed by a {@link org.springframework.web.client.RestClient} configured in
 * {@link org.example.repo2cloud.config.BuildServerConfig}.</p>
 *
 * <p>Every method maps 1-to-1 to a Build Server REST endpoint.</p>
 */
public interface BuildServerClient {

    @PostExchange("/deploy")
    DeploymentResponseDto deploy(@RequestBody DeployRequestDto request);

    @GetExchange("/deployments/{id}")
    DeploymentResponseDto getDeployment(@PathVariable("id") Long id);

    @GetExchange("/deployments")
    List<DeploymentResponseDto> getAllDeployments();

    @GetExchange("/deployments/{id}/logs")
    List<DeploymentLogDto> getLogs(@PathVariable("id") Long id);

    @PostExchange("/deployments/{id}/stop")
    DeploymentResponseDto stop(@PathVariable("id") Long id);

    @DeleteExchange("/deployments/{id}")
    void delete(@PathVariable("id") Long id);

    @PostExchange("/deployments/{id}/start")
    DeploymentResponseDto start(@PathVariable("id") Long id);

    @GetExchange("/deployments/user/{userId}")
    List<DeploymentDto> getDeploymentsByUser(@PathVariable("userId") Long userId);
}
